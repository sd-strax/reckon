// Package wirets writes the workbench's TypeScript for the Go wire types
// (adr/0278). It reads each type by reflection. Every type gets a TypeScript
// type, and a type the workbench receives also gets a decoder built from the
// combinators in workbench/src/wire/decode.ts. What a decoder requires is what
// encoding/json always sends, so the rules here are encoding/json's:
//
//   - a field without omitempty is required, with omitempty or omitzero it may
//     be absent or null, and a pointer without either is a required key whose
//     value may be null; omitempty never leaves out a struct, so a struct
//     field stays required;
//   - a list or a map may be null, which reads as empty;
//   - an int64 is a number, and uint, uint64 and uintptr are refused;
//   - a map[string]any is an object of opaque values, and json.RawMessage
//     and any are opaque;
//   - a named string type with a WireValues method is a union of its words,
//     and its decoder refuses any other word;
//   - a time.Time is an RFC 3339 string, and a uuid.UUID is a string in its
//     canonical text form; any other type with its own MarshalJSON or
//     MarshalText is refused unless listed here;
//   - an embedded struct without a tag name is flattened into its parent.
//
// The output depends only on the types and the order they are registered in.
package wirets

import (
	"bytes"
	"encoding"
	"encoding/json"
	"errors"
	"fmt"
	"reflect"
	"slices"
	"strconv"
	"strings"
	"time"
	"unicode"

	"github.com/google/uuid"
)

// Generator collects the types one TypeScript file holds.
type Generator struct {
	source string
	roots  []root
	consts []constant
	names  map[reflect.Type]string
}

type root struct {
	name    string // the decoder's name; empty for a type alone
	typ     reflect.Type
	decoded bool
}

type constant struct {
	name  string
	value int
}

// New starts a file for the wire types of the Go package source, which the
// header names.
func New(source string) *Generator {
	return &Generator{source: source, names: map[reflect.Type]string{}}
}

// Name gives t the TypeScript type name ts, in place of its Go name. Its
// decoder, unless t is registered with a name of its own, is ts in camel
// case. It is for two Go types whose names give one TypeScript name.
func (g *Generator) Name(t reflect.Type, ts string) {
	g.names[t] = ts
}

// Decoder registers a type the workbench receives: a result, a response or a
// notification. It gets a type and an exported decoder named name.
func (g *Generator) Decoder(name string, t reflect.Type) {
	g.roots = append(g.roots, root{name: name, typ: t, decoded: true})
}

// Type registers a type the workbench sends: a request body or params. It
// gets a type and no decoder.
func (g *Generator) Type(t reflect.Type) {
	g.roots = append(g.roots, root{typ: t})
}

// Decoded lists the types registered with Decoder, in registration order.
func (g *Generator) Decoded() []reflect.Type {
	var out []reflect.Type
	for _, r := range g.roots {
		if r.decoded {
			out = append(out, r.typ)
		}
	}
	return out
}

// Const registers a number constant, such as a protocol version.
func (g *Generator) Const(name string, value int) {
	g.consts = append(g.consts, constant{name: name, value: value})
}

// Command is how the header and a stale file's failure say to regenerate.
const Command = "make wire-fixtures"

// Generate writes the TypeScript file, or every reason a type was refused.
func (g *Generator) Generate() ([]byte, error) {
	w := &writer{
		decls:     map[reflect.Type]*decl{},
		decoded:   map[reflect.Type]bool{},
		rootName:  map[reflect.Type]string{},
		tsNames:   map[string]reflect.Type{},
		decNames:  map[string]reflect.Type{},
		used:      map[string]bool{},
		refusedAt: map[string]bool{},
		names:     g.names,
	}
	// Every root's name is known before any type is marked, so the order of
	// registration does not change what is written.
	for _, r := range g.roots {
		if r.typ.Name() == "" {
			w.refuse(r.typ.String(), "a registered type needs a name")
			continue
		}
		prev, ok := w.rootName[r.typ]
		switch {
		case !r.decoded:
			if !ok {
				w.rootName[r.typ] = ""
			}
		case prev != "" && prev != r.name:
			w.refuse(r.typ.String(), fmt.Sprintf("registered as both %s and %s", prev, r.name))
		default:
			w.rootName[r.typ] = r.name
		}
	}
	for _, r := range g.roots {
		if r.decoded && r.typ.Name() != "" {
			w.markDecoded(r.typ, map[reflect.Type]bool{})
		}
	}
	for _, r := range g.roots {
		if r.typ.Name() != "" {
			w.named(r.typ, r.typ.String(), false)
		}
	}
	if len(w.errs) > 0 {
		return nil, errors.Join(w.errs...)
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/wirets from the wire types of %s. DO NOT EDIT.\n", g.source)
	fmt.Fprintf(&b, "// Run `%s` to write it again (adr/0278).\n", Command)
	if imports := w.imports(); imports != "" {
		fmt.Fprintf(&b, "import { %s } from \"./decode\";\n", imports)
	}
	if len(g.consts) > 0 {
		b.WriteString("\n")
		for _, c := range g.consts {
			fmt.Fprintf(&b, "export const %s = %d;\n", c.name, c.value)
		}
	}
	for _, d := range w.order {
		b.WriteString("\n")
		b.WriteString(d.text)
	}
	return b.Bytes(), nil
}

// words is the method a named string type lists its words with. It is
// wirefixture.Words, restated so this package does not import a test helper.
type words interface {
	WireValues() []string
}

var (
	timeType      = reflect.TypeFor[time.Time]()
	rawType       = reflect.TypeFor[json.RawMessage]()
	wordsType     = reflect.TypeFor[words]()
	marshalerType = reflect.TypeFor[json.Marshaler]()
	textType      = reflect.TypeFor[encoding.TextMarshaler]()
)

// listed are the types with their own marshaling whose JSON is known.
var listed = map[reflect.Type]expr{
	timeType:                     {ts: "string", dec: "str"}, // RFC 3339
	rawType:                      {ts: "unknown", dec: "anything"},
	reflect.TypeFor[uuid.UUID](): {ts: "string", dec: "str"}, // its canonical text form
}

// expr is a type's TypeScript and decoder. When null is set the value may also
// be null, and ts and dec are its form when it is not.
type expr struct {
	ts, dec string
	null    bool
}

// decl is a named TypeScript declaration: a struct, a word list, or a
// registered type.
type decl struct {
	typ     reflect.Type
	tsName  string
	decName string // empty when no decoder is written
	export  bool   // the decoder is exported
	// exportAs is the name a decoder is exported under when that name is a
	// reserved word, which a const cannot have.
	exportAs string
	done     bool
	text     string
}

type writer struct {
	decls     map[reflect.Type]*decl
	order     []*decl
	decoded   map[reflect.Type]bool
	rootName  map[reflect.Type]string
	tsNames   map[string]reflect.Type
	decNames  map[string]reflect.Type
	used      map[string]bool
	errs      []error
	refusedAt map[string]bool
	names     map[reflect.Type]string
}

func (w *writer) refuse(at, why string) {
	if w.refusedAt[at] {
		return
	}
	w.refusedAt[at] = true
	w.errs = append(w.errs, fmt.Errorf("%s: %s (adr/0278)", at, why))
}

func (w *writer) use(name string) {
	w.used[name] = true
}

func (w *writer) imports() string {
	var names []string
	for n := range w.used {
		names = append(names, n)
	}
	slices.Sort(names)
	if len(w.decNames) > 0 {
		names = append(names, "type Decoder")
	}
	return strings.Join(names, ", ")
}

// markDecoded records every named type reachable from t as needing a decoder.
func (w *writer) markDecoded(t reflect.Type, seen map[reflect.Type]bool) {
	if seen[t] {
		return
	}
	seen[t] = true
	if _, ok := listed[t]; ok {
		return
	}
	if w.isDecl(t) {
		w.decoded[t] = true
	}
	switch t.Kind() {
	case reflect.Pointer, reflect.Slice, reflect.Array:
		w.markDecoded(t.Elem(), seen)
	case reflect.Map:
		w.markDecoded(t.Key(), seen)
		w.markDecoded(t.Elem(), seen)
	case reflect.Struct:
		fs, err := fields(t)
		if err != nil {
			return
		}
		for _, f := range fs {
			w.markDecoded(f.typ, seen)
		}
	}
}

// isDecl reports whether t is written as a declaration of its own.
func (w *writer) isDecl(t reflect.Type) bool {
	if _, ok := listed[t]; ok || t.Name() == "" {
		return false
	}
	if _, ok := w.rootName[t]; ok {
		return true
	}
	return t.Kind() == reflect.Struct || isWords(t)
}

// isWords reports whether t lists its words.
func isWords(t reflect.Type) bool {
	return t.Kind() != reflect.Pointer && t.Kind() != reflect.Interface &&
		(t.Implements(wordsType) || reflect.PointerTo(t).Implements(wordsType))
}

// wordsOf returns the words t lists.
func wordsOf(t reflect.Type) []string {
	if t.Implements(wordsType) {
		return reflect.Zero(t).Interface().(words).WireValues()
	}
	return reflect.New(t).Interface().(words).WireValues()
}

// named returns the reference to t's declaration, writing it first if needed.
// A decoder still being written is reached through lazy, for a recursive type.
func (w *writer) named(t reflect.Type, at string, withDec bool) expr {
	d := w.decls[t]
	if d == nil {
		d = w.declare(t, at)
		if d == nil {
			return expr{}
		}
		w.write(d, at)
	}
	e := expr{ts: d.tsName}
	if withDec {
		if d.done {
			e.dec = d.decName
		} else {
			w.use("lazy")
			e.dec = "lazy(() => " + d.decName + ")"
		}
	}
	return e
}

// declare names t's declaration, refusing a name another type has.
func (w *writer) declare(t reflect.Type, at string) *decl {
	if strings.ContainsAny(t.Name(), "[]") {
		w.refuse(at, fmt.Sprintf("%s is a generic type; give the instance a name of its own", t))
		return nil
	}
	tsName := pascal(t.Name())
	if name, ok := w.names[t]; ok {
		tsName = name
	}
	d := &decl{typ: t, tsName: tsName}
	if other, ok := w.tsNames[d.tsName]; ok && other != t {
		w.refuse(at, fmt.Sprintf("%s and %s both give the TypeScript type %s", other, t, d.tsName))
		return nil
	}
	w.tsNames[d.tsName] = t
	if w.decoded[t] {
		d.decName = camel(tsName)
		if name := w.rootName[t]; name != "" {
			d.export = true
			if reserved[name] {
				// The const keeps the type's name and is exported under the
				// registered one.
				d.exportAs = name
			} else {
				d.decName = name
			}
		}
		if reserved[d.decName] {
			w.refuse(at, fmt.Sprintf("the decoder name %s is a reserved word in TypeScript", d.decName))
			return nil
		}
		if other, ok := w.decNames[d.decName]; ok && other != t {
			w.refuse(at, fmt.Sprintf("%s and %s both give the decoder %s", other, t, d.decName))
			return nil
		}
		w.decNames[d.decName] = t
	}
	w.decls[t] = d
	return d
}

// write writes d's declaration, after every declaration it depends on.
func (w *writer) write(d *decl, at string) {
	t := d.typ
	withDec := d.decName != ""
	var b strings.Builder
	var dec string
	switch {
	case isWords(t) && t.Kind() == reflect.String:
		list := wordsOf(t)
		if len(list) == 0 {
			w.refuse(at, fmt.Sprintf("%s lists no words", t))
			return
		}
		quoted := make([]string, len(list))
		for i, word := range list {
			quoted[i] = quote(word)
		}
		fmt.Fprintf(&b, "export type %s = %s;\n", d.tsName, strings.Join(quoted, " | "))
		if withDec {
			w.use("oneOf")
			dec = "oneOf(" + strings.Join(quoted, ", ") + ")"
		}
	case t.Kind() == reflect.Struct && !w.marshals(t, at):
		fs, ts, decs := w.object(t, at, withDec)
		if len(fs) == 0 {
			fmt.Fprintf(&b, "export type %s = Record<string, never>;\n", d.tsName)
			if withDec {
				w.use("object")
				dec = "object({})"
			}
			break
		}
		fmt.Fprintf(&b, "export interface %s {\n", d.tsName)
		for _, line := range ts {
			fmt.Fprintf(&b, "  %s;\n", line)
		}
		b.WriteString("}\n")
		if withDec {
			w.use("object")
			var o strings.Builder
			o.WriteString("object({\n")
			for _, line := range decs {
				fmt.Fprintf(&o, "  %s,\n", line)
			}
			o.WriteString("})")
			dec = o.String()
		}
	default:
		e := w.value(t, at, withDec, true)
		fmt.Fprintf(&b, "export type %s = %s;\n", d.tsName, e.tsWithNull())
		dec = e.decWithNull(w)
	}
	if withDec {
		keyword := "const"
		if d.export {
			keyword = "export const"
		}
		if d.exportAs != "" {
			keyword = "const"
		}
		fmt.Fprintf(&b, "%s %s: Decoder<%s> = %s;\n", keyword, d.decName, d.tsName, dec)
		if d.exportAs != "" {
			fmt.Fprintf(&b, "export { %s as %s };\n", d.decName, d.exportAs)
		}
	}
	d.text = b.String()
	d.done = true
	w.order = append(w.order, d)
}

// object returns a struct's fields, as TypeScript members and as decoder
// entries.
func (w *writer) object(t reflect.Type, at string, withDec bool) ([]field, []string, []string) {
	fs, err := fields(t)
	if err != nil {
		w.refuse(at, err.Error())
		return nil, nil, nil
	}
	var ts, decs []string
	for _, f := range fs {
		fat := at + "." + f.name
		ft := f.typ
		pointer := ft.Kind() == reflect.Pointer
		if pointer {
			ft = ft.Elem()
		}
		e := w.value(ft, fat, withDec, false)
		if pointer {
			e.null = true
		}
		key := propertyKey(f.name)
		switch {
		case f.omitZero || f.viaPointer || f.omitEmpty && omittable(f.typ):
			ts = append(ts, key+"?: "+e.ts)
			if withDec {
				w.use("optional")
				decs = append(decs, key+": optional("+e.dec+")")
			}
		default:
			ts = append(ts, key+": "+e.tsWithNull())
			if withDec {
				decs = append(decs, key+": "+e.decWithNull(w))
			}
		}
	}
	return fs, ts, decs
}

// omittable reports whether omitempty can leave out a value of t: it never
// leaves out a struct or a non-empty array.
func omittable(t reflect.Type) bool {
	switch t.Kind() {
	case reflect.Struct:
		return false
	case reflect.Array:
		return t.Len() == 0
	}
	return true
}

// marshals refuses t, or the type t points to, when it has its own
// MarshalJSON or MarshalText and is not listed.
func (w *writer) marshals(t reflect.Type, at string) bool {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if _, ok := listed[t]; ok {
		return false
	}
	for _, m := range []reflect.Type{marshalerType, textType} {
		if t.Implements(m) || reflect.PointerTo(t).Implements(m) {
			w.refuse(at, fmt.Sprintf("%s has its own %s, so its JSON is not what its fields say; list it in internal/wirets or drop the method", t, m.Method(0).Name))
			return true
		}
	}
	return false
}

// value returns the TypeScript and decoder for a value of type t. top is set
// when t is the declaration being written, which is then spelled out.
func (w *writer) value(t reflect.Type, at string, withDec, top bool) expr {
	if e, ok := listed[t]; ok {
		if withDec {
			w.use(e.dec)
		}
		return e
	}
	if w.marshals(t, at) {
		return expr{}
	}
	if !top && w.isDecl(t) {
		return w.named(t, at, withDec)
	}
	use := func(ts, dec string) expr {
		if withDec {
			w.use(dec)
		}
		return expr{ts: ts, dec: dec}
	}
	switch t.Kind() {
	case reflect.String:
		if isWords(t) {
			return w.named(t, at, withDec)
		}
		return use("string", "str")
	case reflect.Bool:
		return use("boolean", "bool")
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Float32, reflect.Float64:
		if isWords(t) {
			w.refuse(at, fmt.Sprintf("%s lists words but is not a string", t))
		}
		return use("number", "num")
	case reflect.Uint, reflect.Uint64, reflect.Uintptr:
		w.refuse(at, fmt.Sprintf("%s is refused: a JSON number above 2^53 loses digits in TypeScript; send an int64 count or a string identifier", t))
		return expr{}
	case reflect.Interface:
		if t.NumMethod() != 0 {
			w.refuse(at, fmt.Sprintf("%s is an interface with methods, so what it sends is not known", t))
			return expr{}
		}
		return use("unknown", "anything")
	case reflect.Pointer:
		e := w.value(t.Elem(), at, withDec, false)
		e.null = true
		return e
	case reflect.Slice, reflect.Array:
		if t.Kind() == reflect.Slice && t.Elem().Kind() == reflect.Uint8 {
			// encoding/json sends a []byte as a base64 string, and nil as null.
			e := use("string", "str")
			e.null = true
			return e
		}
		e := w.value(t.Elem(), at+"[]", withDec, false)
		r := expr{ts: arrayOf(e.tsWithNull())}
		if withDec {
			w.use("list")
			r.dec = "list(" + e.decWithNull(w) + ")"
		}
		return r
	case reflect.Map:
		return w.mapValue(t, at, withDec)
	case reflect.Struct:
		_, ts, decs := w.object(t, at, withDec)
		r := expr{ts: "{ " + strings.Join(ts, "; ") + " }"}
		if len(ts) == 0 {
			r.ts = "Record<string, never>"
		}
		if withDec {
			w.use("object")
			r.dec = "object({ " + strings.Join(decs, ", ") + " })"
			if len(decs) == 0 {
				r.dec = "object({})"
			}
		}
		return r
	}
	w.refuse(at, fmt.Sprintf("%s cannot be sent as JSON", t))
	return expr{}
}

// mapValue returns a map's TypeScript and decoder: an object, whose keys are
// checked when the map is keyed by a word type. A map[string]any is an object
// of opaque values.
func (w *writer) mapValue(t reflect.Type, at string, withDec bool) expr {
	key := t.Key()
	if w.marshals(key, at+" (key)") {
		return expr{}
	}
	val := w.value(t.Elem(), at+"[]", withDec, false)
	switch key.Kind() {
	case reflect.String:
		if isWords(key) {
			k := w.named(key, at+" (key)", withDec)
			r := expr{ts: "Partial<Record<" + k.ts + ", " + val.tsWithNull() + ">>"}
			if withDec {
				w.use("recordOf")
				r.dec = "recordOf(" + k.dec + ", " + val.decWithNull(w) + ")"
			}
			return r
		}
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint8, reflect.Uint16, reflect.Uint32:
	default:
		w.refuse(at, fmt.Sprintf("%s has a key encoding/json cannot send, or one above 2^53", t))
		return expr{}
	}
	r := expr{ts: "Record<string, " + val.tsWithNull() + ">"}
	if withDec {
		w.use("record")
		r.dec = "record(" + val.decWithNull(w) + ")"
	}
	return r
}

func (e expr) tsWithNull() string {
	if e.null {
		return e.ts + " | null"
	}
	return e.ts
}

func (e expr) decWithNull(w *writer) string {
	if e.null {
		w.use("nullable")
		return "nullable(" + e.dec + ")"
	}
	return e.dec
}

// arrayOf writes a list of ts, in parentheses when ts is a union.
func arrayOf(ts string) string {
	if strings.Contains(ts, " | ") {
		return "(" + ts + ")[]"
	}
	return ts + "[]"
}

// propertyKey writes a key bare when it is an identifier, quoted otherwise.
func propertyKey(name string) string {
	for i, c := range name {
		identifier := c == '_' || c == '$' || unicode.IsLetter(c) || i > 0 && unicode.IsDigit(c)
		if !identifier {
			return quote(name)
		}
	}
	return name
}

func quote(s string) string {
	return strconv.Quote(s)
}

// pascal writes a Go type name as a TypeScript type name.
func pascal(name string) string {
	return strings.ToUpper(name[:1]) + name[1:]
}

// camel writes a Go type name as a decoder name: SOPOutline becomes
// sopOutline, and turnUsage stays as it is.
func camel(name string) string {
	runes := []rune(name)
	n := 0
	for n < len(runes) && unicode.IsUpper(runes[n]) {
		n++
	}
	if n > 1 && n < len(runes) {
		n-- // the last capital starts the next word
	}
	for i := range n {
		runes[i] = unicode.ToLower(runes[i])
	}
	return string(runes)
}

// reserved are the words TypeScript does not allow as a const's name.
var reserved = map[string]bool{
	"break": true, "case": true, "catch": true, "class": true, "const": true, "continue": true,
	"debugger": true, "default": true, "delete": true, "do": true, "else": true, "enum": true,
	"export": true, "extends": true, "false": true, "finally": true, "for": true, "function": true,
	"if": true, "import": true, "in": true, "instanceof": true, "new": true, "null": true,
	"return": true, "super": true, "switch": true, "this": true, "throw": true, "true": true,
	"try": true, "typeof": true, "var": true, "void": true, "while": true, "with": true,
	"let": true, "static": true, "yield": true, "await": true, "implements": true,
	"interface": true, "package": true, "private": true, "protected": true, "public": true,
}
