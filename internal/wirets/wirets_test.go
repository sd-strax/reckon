type tags []string

type tagged struct {
	Tags tags `json:"tags"`
}

// TestGenerate_RegistrationOrder writes the same decoders whichever order the
// types are registered in: a type registered alone after a decoder reaches
// it, or before it is registered as a decoder, still gets its decoder.
func TestGenerate_RegistrationOrder(t *testing.T) {
	want := generate(t, func(g *Generator) {
		g.Type(reflect.TypeFor[tags]())
		g.Decoder("tagged", reflect.TypeFor[tagged]())
	})
	requireLines(t, want, "export type Tags = string[];", "const tags: Decoder<Tags> = list(str);", "  tags: tags,")
	got := generate(t, func(g *Generator) {
		g.Decoder("tagged", reflect.TypeFor[tagged]())
		g.Type(reflect.TypeFor[tags]())
	})
	requireLines(t, got, "export type Tags = string[];", "const tags: Decoder<Tags> = list(str);", "  tags: tags,")
	both := generate(t, func(g *Generator) {
		g.Type(reflect.TypeFor[tagged]())
		g.Decoder("tagged", reflect.TypeFor[tagged]())
	})
	requireLines(t, both, "export const tagged: Decoder<Tagged> = object({")
}
