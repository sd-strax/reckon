type params struct {
	ID    string `json:"id"`
	Color color  `json:"color"`
}

func generate(t *testing.T, build func(*Generator)) string {
	t.Helper()
	g := New("internal/wirets")
	build(g)
	src, err := g.Generate()
	if err != nil {
		t.Fatal(err)
	}
	return string(src)
}

func requireLines(t *testing.T, src string, want ...string) {
	t.Helper()
	for _, w := range want {
		if !strings.Contains(src, w) {
			t.Errorf("output lacks %q\n%s", w, src)
		}
	}
}

// TestGenerate_Rules holds each contract rule (adr/0278) to the TypeScript it
// writes.
func TestGenerate_Rules(t *testing.T) {
	src := generate(t, func(g *Generator) {
		g.Const("VERSION", 3)
		g.Decoder("everything", reflect.TypeFor[everything]())
	})
	requireLines(t, src,
		"// Code generated by internal/wirets from the wire types of internal/wirets. DO NOT EDIT.",
		"// Run `make wire-fixtures` to write it again (adr/0278).",
		"export const VERSION = 3;",
		// A field without omitempty is required.
		"  required: string;", "  required: str,",
		// omitempty and omitzero make a field optional.
		"  optional?: string;", "  optional: optional(str),",
		"  zero?: number;", "  zero: optional(num),",
		// A pointer without omitempty is a required key that may be null.
		"  nullable: Inner | null;", "  nullable: nullable(inner),",
		"  opt_pointer?: Inner;", "  opt_pointer: optional(inner),",
		// omitempty never leaves out a struct, so it stays required.
		"  struct: Inner;", "  struct: inner,",
		// Lists and maps read null as empty.
		"  list: string[];", "  list: list(str),",
		"  map: Record<string, number>;", "  map: record(num),",
		"  nested: Record<string, Inner | null>;", "  nested: record(nullable(inner)),",
		// A map keyed by words checks its keys.
		"  by_color: Partial<Record<Color, number>>;", "  by_color: recordOf(color, num),",
		// An int64 is a number.
		"  count: number;", "  count: num,",
		// Raw payloads are opaque.
		"  raw: unknown;", "  raw: anything,",
		"  any: unknown;", "  any: anything,",
		"  opaque: unknown;", "  opaque: anything,",
		// A time.Time is a string.
		"  when: string;", "  when: str,",
		// A word type is a union, and its decoder refuses other words.
		`export type Color = "RED" | "BLUE";`,
		`const color: Decoder<Color> = oneOf("RED", "BLUE");`,
		"  color: Color;", "  color: color,",
		"  colors?: Color[];", "  colors: optional(list(color)),",
		// A []byte is a base64 string, or null.
		"  bytes: string | null;", "  bytes: nullable(str),",
		// Field names follow encoding/json, and odd keys are quoted.
		"  Untagged: boolean;",
		`  "x-dashed": string;`, `  "x-dashed": str,`,
		"  anonymous: { A: number };", "  anonymous: object({ A: num }),",
		// Embedded fields are flattened; a field reached through an embedded
		// pointer may be absent; the shallower of two names wins.
		"  deep: string;", "  via_pointer?: string;", "  shared: number;",
		// A registered type's decoder is exported; a nested one is not.
		"export const everything: Decoder<Everything> = object({",
		"const inner: Decoder<Inner> = object({",
		`import { anything, bool, list, nullable, num, object, oneOf, optional, record, recordOf, str, type Decoder } from "./decode";`,
	)
	for _, absent := range []string{"Skipped", "unexported", "shared: string"} {
		if strings.Contains(src, absent) {
			t.Errorf("output names %q, which encoding/json does not send", absent)
		}
	}
	// Every field is read, in the order Go writes them.
	if strings.Index(src, "  deep: str,") > strings.Index(src, "  via_pointer: optional(str),") {
		t.Errorf("fields are not in encoding/json's order\n%s", src)
	}
}

// TestGenerate_Recursive reaches a type that holds itself through lazy.
func TestGenerate_Recursive(t *testing.T) {
	src := generate(t, func(g *Generator) { g.Decoder("node", reflect.TypeFor[node]()) })
	requireLines(t, src,
		"  children: (Node | null)[];",
		"  children: list(nullable(lazy(() => node))),",
	)
}

// TestGenerate_TypeOnly writes a type and no decoder for what the workbench
// sends.
func TestGenerate_TypeOnly(t *testing.T) {
	src := generate(t, func(g *Generator) { g.Type(reflect.TypeFor[params]()) })
	requireLines(t, src, "export interface Params {", "  color: Color;", `export type Color = "RED" | "BLUE";`)
	if strings.Contains(src, "Decoder") || strings.Contains(src, "import") {
		t.Errorf("a type alone has a decoder or an import\n%s", src)
	}
}

// TestGenerate_Deterministic writes the same bytes every time.
func TestGenerate_Deterministic(t *testing.T) {
	build := func(g *Generator) {
		g.Decoder("everything", reflect.TypeFor[everything]())
		g.Type(reflect.TypeFor[params]())
	}
	first := generate(t, build)
	for range 20 {
		if got := generate(t, build); got != first {
			t.Fatal("two runs wrote different output")
		}
	}
}

type marshals struct{}

func (marshals) MarshalJSON() ([]byte, error) { return []byte(`"x"`), nil }

type textMarshals struct{}

func (*textMarshals) MarshalText() ([]byte, error) { return []byte("x"), nil }

type noWords string

func (noWords) WireValues() []string { return nil }

type intWords int

func (intWords) WireValues() []string { return []string{"A"} }

type (
	withMarshaler struct {
		M marshals `json:"m"`
	}
	withTextMarshaler struct {
		M textMarshals `json:"m"`
	}
	withMarshalerPointer struct {
		M *marshals `json:"m"`
	}
	withUint64 struct {
		N uint64 `json:"n"`
	}
	withUint struct {
		N []uint `json:"n"`
	}
	withUint64Key struct {
		M map[uint64]string `json:"m"`
	}
	withInterface struct {
		S interface{ String() string } `json:"s"`
	}
	withNoWords struct {
		W noWords `json:"w"`
	}
	withIntWords struct {
		W intWords `json:"w"`
	}
	withString struct {
		N int `json:"n,string"`
	}
	withChannel struct {
		C chan int `json:"c"`
	}
	caseWord struct{}
)

// TestGenerate_Refuses names the type and the reason for each refusal.
func TestGenerate_Refuses(t *testing.T) {
	cases := []struct {
		name string
		typ  reflect.Type
		want string
	}{
		{"a custom MarshalJSON", reflect.TypeFor[withMarshaler](), "has its own MarshalJSON"},
		{"a custom MarshalText on the pointer", reflect.TypeFor[withTextMarshaler](), "has its own MarshalText"},
		{"a custom marshaler behind a pointer", reflect.TypeFor[withMarshalerPointer](), "has its own MarshalJSON"},
		{"a uint64", reflect.TypeFor[withUint64](), "uint64 is refused"},
		{"a uint", reflect.TypeFor[withUint](), "uint is refused"},
		{"a uint64 map key", reflect.TypeFor[withUint64Key](), "a key encoding/json cannot send"},
		{"an interface with methods", reflect.TypeFor[withInterface](), "an interface with methods"},
		{"a word type with no words", reflect.TypeFor[withNoWords](), "lists no words"},
		{"a word type that is not a string", reflect.TypeFor[withIntWords](), "lists words but is not a string"},
		{"the ,string option", reflect.TypeFor[withString](), "the `,string` option"},
		{"a channel", reflect.TypeFor[withChannel](), "cannot be sent as JSON"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			g := New("x")
			g.Decoder("x", c.typ)
			_, err := g.Generate()
			if err == nil || !strings.Contains(err.Error(), c.want) {
				t.Fatalf("err = %v; want it to say %q", err, c.want)
			}
			if !strings.Contains(err.Error(), c.typ.String()) {
				t.Errorf("err = %v; want it to name %s", err, c.typ)
			}
		})
	}

	t.Run("a reserved word as a decoder name", func(t *testing.T) {
		g := New("x")
		g.Decoder("case", reflect.TypeFor[caseWord]())
		if _, err := g.Generate(); err == nil || !strings.Contains(err.Error(), "reserved word") {
			t.Fatalf("err = %v", err)
		}
	})
	t.Run("an unnamed type", func(t *testing.T) {
		g := New("x")
		g.Decoder("x", reflect.TypeFor[struct{}]())
		if _, err := g.Generate(); err == nil || !strings.Contains(err.Error(), "needs a name") {
			t.Fatalf("err = %v", err)
		}
	})
}

